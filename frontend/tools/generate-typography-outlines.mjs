#!/usr/bin/env node
/**
 * Generates vector outlines for the hero 3D typography (Node only — no Python).
 *
 * Tamil needs complex-script shaping (vowel-sign reordering, split vowels, pulli placement), which
 * three.js' TextGeometry cannot do. fontkit shapes the text here and the glyph outlines are written
 * as SVG path data; the browser extrudes them into real 3D geometry (see hero-typography-3d.ts).
 *
 * Usage (from frontend/):  npm run generate:headline
 * Fonts (SIL OFL 1.1, from devDependencies): Anek Tamil ExtraBold, Montserrat Black.
 * Output (committed): src/app/pages/home/hero/typography/hero-headline-outlines.ts
 * Re-run only when the headline text or fonts change.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as fontkit from 'fontkit';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(root, 'src/app/pages/home/hero/typography/hero-headline-outlines.ts');
const font = (pkg, file) => fontkit.openSync(resolve(root, 'node_modules/@fontsource', pkg, 'files', file));

// Language, font, lines, tracking (1000-unit em).
const JOBS = [
  { lang: 'en', font: font('montserrat', 'montserrat-latin-900-normal.woff'), lines: ['ORGANIZE', 'AND UNITE'], tracking: -12 },
  { lang: 'ta', font: font('anek-tamil', 'anek-tamil-tamil-800-normal.woff'), lines: ['அமைப்பாய்த்', 'திரள்வோம்'], tracking: 0 }
];

const num = (value) => String(Math.round(value * 10) / 10);

function shapeLine(face, text, tracking) {
  const scale = 1000 / face.unitsPerEm;
  const run = face.layout(text);
  const commands = [];
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  let x = 0;

  run.glyphs.forEach((glyph, index) => {
    const pos = run.positions[index];
    const ox = x + pos.xOffset * scale;
    const oy = pos.yOffset * scale;
    // Font units (y-up) -> 1000-unit em, y flipped (SVG is y-down).
    const px = (fx) => num(ox + fx * scale);
    const py = (fy) => num(-(oy + fy * scale));
    for (const { command, args } of glyph.path.commands) {
      if (command === 'moveTo') commands.push(`M${px(args[0])} ${py(args[1])}`);
      else if (command === 'lineTo') commands.push(`L${px(args[0])} ${py(args[1])}`);
      else if (command === 'quadraticCurveTo') commands.push(`Q${px(args[0])} ${py(args[1])} ${px(args[2])} ${py(args[3])}`);
      else if (command === 'bezierCurveTo') commands.push(`C${px(args[0])} ${py(args[1])} ${px(args[2])} ${py(args[3])} ${px(args[4])} ${py(args[5])}`);
      else if (command === 'closePath') commands.push('Z');
    }
    const box = glyph.bbox;
    if (Number.isFinite(box.minX) && box.maxX > box.minX) {
      minX = Math.min(minX, ox + box.minX * scale);
      maxX = Math.max(maxX, ox + box.maxX * scale);
      minY = Math.min(minY, -(oy + box.maxY * scale));
      maxY = Math.max(maxY, -(oy + box.minY * scale));
    }
    x += pos.xAdvance * scale + tracking;
  });

  return { path: commands.join(''), bounds: [minX, minY, maxX, maxY].map(num) };
}

const out = [
  '// GENERATED by tools/generate-typography-outlines.mjs (npm run generate:headline) — do not edit by hand.',
  '// Fonts: Anek Tamil ExtraBold and Montserrat Black (SIL Open Font License 1.1).',
  '// Coordinates: 1000-unit em, y-down, baseline at y = 0, each line starts at x = 0.',
  '',
  "export type HeadlineLanguage = 'en' | 'ta';",
  'export type HeadlineLine = { readonly path: string; readonly bounds: readonly [number, number, number, number] };',
  '',
  'export const HERO_HEADLINE_OUTLINES: Record<HeadlineLanguage, readonly HeadlineLine[]> = {'
];
for (const job of JOBS) {
  out.push(`  ${job.lang}: [`);
  for (const line of job.lines) {
    const { path, bounds } = shapeLine(job.font, line, job.tracking);
    out.push(`    { path: '${path}', bounds: [${bounds.join(', ')}] },`);
  }
  out.push('  ],');
}
out.push('};', '');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`Wrote ${OUT}`);
