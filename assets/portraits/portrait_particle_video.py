#!/usr/bin/env python3
"""
Turn a 2D portrait into a 2.5D particle / wireframe animation and export MP4.

Requirements:
    pip install opencv-python numpy scipy

Example:
    python portrait_particle_video.py --input thiruma.png --output thiruma.mp4

Optional real depth map (same framing as input; white = nearer):
    python portrait_particle_video.py --input thiruma.png --depth depth.png --output thiruma.mp4

The default depth is an approximation derived from image luminance. For better
3D shape, supply a depth map generated by a depth-estimation tool.
"""
import argparse
import os
import sys
import cv2
import numpy as np
from scipy.spatial import cKDTree


def parse_args():
    p = argparse.ArgumentParser(description="Render a 2.5D particle portrait video.")
    p.add_argument("--input", required=True, help="Input portrait image (PNG/JPG; transparent PNG recommended).")
    p.add_argument("--output", default="particle_portrait.mp4", help="Output MP4 filename.")
    p.add_argument("--depth", default=None, help="Optional depth-map image; white=near, black=far.")
    p.add_argument("--width", type=int, default=1080, help="Output video width.")
    p.add_argument("--height", type=int, default=1350, help="Output video height.")
    p.add_argument("--fps", type=int, default=30, help="Frames per second.")
    p.add_argument("--duration", type=float, default=6.0, help="Total video duration in seconds.")
    p.add_argument("--formation", type=float, default=3.0, help="Particle formation duration in seconds.")
    p.add_argument("--particles", type=int, default=18000, help="Number of particles.")
    p.add_argument("--line-density", type=float, default=0.75, help="Wireframe amount, 0 to 1.")
    p.add_argument("--line-distance", type=float, default=0.055, help="Maximum neighbour distance in normalized portrait units.")
    p.add_argument("--particle-size", type=float, default=1.6, help="Particle radius in output pixels.")
    p.add_argument("--glow", type=float, default=0.65, help="Glow strength, 0 to 1.")
    p.add_argument("--depth-scale", type=float, default=0.85, help="3D depth strength.")
    p.add_argument("--rotation", type=float, default=10.0, help="Total Y rotation in degrees over the video.")
    p.add_argument("--background-threshold", type=int, default=12, help="For non-transparent images, discard pixels darker than this. Set 0 to use full image.")
    p.add_argument("--seed", type=int, default=7, help="Random seed.")
    p.add_argument("--quality", choices=["preview", "high", "ultra"], default="high",
                   help="preview=quick/small, high=default, ultra=more particles and resolution.")
    return p.parse_args()


def load_images(args):
    image = cv2.imread(args.input, cv2.IMREAD_UNCHANGED)
    if image is None:
        raise FileNotFoundError(f"Cannot read input image: {args.input}")
    if image.ndim == 2:
        image = cv2.cvtColor(image, cv2.COLOR_GRAY2BGRA)
    elif image.shape[2] == 3:
        image = cv2.cvtColor(image, cv2.COLOR_BGR2BGRA)

    # Keep source aspect ratio inside the output frame.
    h, w = image.shape[:2]
    scale = min(args.width / w, args.height / h) * 0.88
    nw, nh = max(2, int(w * scale)), max(2, int(h * scale))
    image = cv2.resize(image, (nw, nh), interpolation=cv2.INTER_AREA)

    canvas = np.zeros((args.height, args.width, 4), dtype=np.uint8)
    x0, y0 = (args.width - nw) // 2, (args.height - nh) // 2
    canvas[y0:y0+nh, x0:x0+nw] = image

    rgb = cv2.cvtColor(canvas[:, :, :3], cv2.COLOR_BGR2RGB)
    alpha = canvas[:, :, 3]
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)

    if args.depth:
        d = cv2.imread(args.depth, cv2.IMREAD_GRAYSCALE)
        if d is None:
            raise FileNotFoundError(f"Cannot read depth map: {args.depth}")
        depth = cv2.resize(d, (args.width, args.height), interpolation=cv2.INTER_CUBIC).astype(np.float32) / 255.0
    else:
        # Approximate depth only; it is not true facial geometry.
        smooth = cv2.GaussianBlur(gray, (0, 0), 17).astype(np.float32) / 255.0
        detail = cv2.Laplacian(gray, cv2.CV_32F)
        detail = np.abs(detail)
        if detail.max() > 0:
            detail /= detail.max()
        depth = np.clip(0.68 * (gray.astype(np.float32) / 255.0) + 0.32 * detail, 0, 1)
        depth = cv2.GaussianBlur(depth, (0, 0), 3)

    if np.any(alpha < 250):
        mask = alpha > 8
    elif args.background_threshold > 0:
        mask = gray > args.background_threshold
    else:
        mask = np.ones(gray.shape, dtype=bool)

    # Give edges and facial detail a little extra sampling probability.
    edges = cv2.Canny(gray, 45, 120).astype(np.float32) / 255.0
    weights = (0.25 + gray.astype(np.float32) / 255.0 * 0.25 + edges * 0.8)
    weights *= mask.astype(np.float32)
    return rgb, depth, weights, mask


def make_particles(args, rgb, depth, weights):
    rng = np.random.default_rng(args.seed)
    h, w = weights.shape
    flat_w = weights.ravel()
    valid = np.flatnonzero(flat_w > 0)
    if len(valid) < args.particles:
        replace = True
    else:
        replace = False
    probs = flat_w[valid].astype(np.float64)
    probs /= probs.sum()
    chosen = rng.choice(valid, size=args.particles, replace=replace, p=probs)
    ys, xs = np.unravel_index(chosen, (h, w))

    # Normalize portrait coordinates to approximately [-1, 1].
    aspect = w / h
    tx = (xs.astype(np.float32) / max(1, w - 1) - 0.5) * 2.0 * aspect
    ty = (0.5 - ys.astype(np.float32) / max(1, h - 1)) * 2.0
    tz = (depth[ys, xs] - 0.5) * args.depth_scale

    target = np.column_stack([tx, ty, tz]).astype(np.float32)
    colors = rgb[ys, xs].astype(np.float32) / 255.0

    # Cinematic red / blue / green tint while retaining portrait luminance.
    luminance = colors @ np.array([0.299, 0.587, 0.114], dtype=np.float32)
    palette = np.array([[1.0, 0.22, 0.30], [0.20, 0.58, 1.0],
                        [0.20, 0.95, 0.62], [0.88, 0.92, 1.0]], dtype=np.float32)
    band = rng.integers(0, len(palette), size=args.particles)
    tint = palette[band]
    colors = np.clip(0.38 * colors + (0.62 * luminance[:, None]) * tint, 0, 1)

    # Initial cloud around the portrait.
    source = np.column_stack([
        rng.uniform(-2.3 * aspect, 2.3 * aspect, args.particles),
        rng.uniform(-2.3, 2.3, args.particles),
        rng.uniform(-1.8, 1.8, args.particles)
    ]).astype(np.float32)

    # Find nearby target points once; lines are not recalculated each frame.
    tree = cKDTree(target[:, :2])
    distances, indices = tree.query(target[:, :2], k=4)
    edges = []
    for i in range(args.particles):
        for j in range(1, 4):
            other = int(indices[i, j])
            if other > i and distances[i, j] < args.line_distance:
                if rng.random() < args.line_density:
                    edges.append((i, other))
    edges = np.asarray(edges, dtype=np.int32).reshape(-1, 2)
    return source, target, colors, edges


def ease(x):
    x = np.clip(x, 0.0, 1.0)
    return x * x * (3.0 - 2.0 * x)


def render(args):
    if args.quality == "preview":
        args.width, args.height = min(args.width, 720), min(args.height, 900)
        args.particles = min(args.particles, 6000)
        args.line_density *= 0.55
    elif args.quality == "ultra":
        args.width, args.height = max(args.width, 1440), max(args.height, 1800)
        args.particles = max(args.particles, 45000)

    rgb, depth, weights, mask = load_images(args)
    source, target, colors, edges = make_particles(args, rgb, depth, weights)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    writer = cv2.VideoWriter(args.output, fourcc, args.fps, (args.width, args.height))
    if not writer.isOpened():
        raise RuntimeError("Could not open MP4 writer. Try a .mp4 output path and install an FFmpeg-enabled OpenCV build.")

    h, w = args.height, args.width
    aspect = w / h
    total_frames = int(args.duration * args.fps)
    formation_frames = max(1, int(args.formation * args.fps))
    rng = np.random.default_rng(args.seed + 1)

    # Precompute edge endpoints for fast line rendering.
    edge_a = edges[:, 0] if len(edges) else np.empty(0, dtype=np.int32)
    edge_b = edges[:, 1] if len(edges) else np.empty(0, dtype=np.int32)

    print(f"Rendering {total_frames} frames | {args.particles:,} particles | {len(edges):,} links")
    for frame in range(total_frames):
        t = frame / args.fps
        progress = ease(frame / formation_frames)
        pos = source + (target - source) * progress

        # Subtle movement after formation; fade it in during assembly.
        wobble = (0.006 + 0.012 * progress) * np.sin(
            t * 1.25 + target[:, 0] * 5.0 + target[:, 1] * 3.0
        )
        pos[:, 2] += wobble

        angle = np.deg2rad(args.rotation) * (t / max(args.duration, 0.001))
        ca, sa = np.cos(angle), np.sin(angle)
        x = pos[:, 0] * ca + pos[:, 2] * sa
        z = -pos[:, 0] * sa + pos[:, 2] * ca
        y = pos[:, 1]

        # Perspective projection.
        focal = 2.6
        denom = np.maximum(1.0, focal - z * 0.28)
        px = (w * 0.5 + (x / denom) * (h * 0.43)).astype(np.int32)
        py = (h * 0.5 - (y / denom) * (h * 0.43)).astype(np.int32)
        visible = (px >= 1) & (px < w-1) & (py >= 1) & (py < h-1)

        frame_img = np.zeros((h, w, 3), dtype=np.uint8)

        # Wireframe gradually appears with the portrait.
        if len(edges) and progress > 0.08:
            take = max(1, int(len(edges) * progress))
            ids_a, ids_b = edge_a[:take], edge_b[:take]
            valid_lines = visible[ids_a] & visible[ids_b]
            ids_a, ids_b = ids_a[valid_lines], ids_b[valid_lines]
            line_color = (65, 48, 100)  # BGR muted blue-violet
            for a, b in zip(ids_a[::2], ids_b[::2]):
                cv2.line(frame_img, (int(px[a]), int(py[a])),
                         (int(px[b]), int(py[b])), line_color, 1, cv2.LINE_AA)

        # Draw particle cores using vectorized pixel writes.
        ids = np.flatnonzero(visible)
        col = np.clip(colors[ids] * 255, 0, 255).astype(np.uint8)
        frame_img[py[ids], px[ids]] = col[:, ::-1]  # RGB to BGR

        # Slightly larger particle centres for readability.
        if args.particle_size >= 1.5:
            offsets = [(-1, 0), (1, 0), (0, -1), (0, 1)]
            for ox, oy in offsets:
                xx, yy = px[ids] + ox, py[ids] + oy
                ok = (xx >= 0) & (xx < w) & (yy >= 0) & (yy < h)
                frame_img[yy[ok], xx[ok]] = col[ok, ::-1]

        if args.glow > 0:
            blurred = cv2.GaussianBlur(frame_img, (0, 0), 5)
            frame_img = cv2.addWeighted(
                frame_img, 1.0, blurred, float(args.glow) * 1.8, 0
            )

        writer.write(frame_img)
        if (frame + 1) % max(1, args.fps) == 0:
            print(f"  {frame+1}/{total_frames} frames ({100*(frame+1)/total_frames:.0f}%)")

    writer.release()
    print(f"Saved video: {os.path.abspath(args.output)}")


if __name__ == "__main__":
    args = parse_args()
    if args.formation > args.duration:
        print("Warning: formation duration exceeds total duration.")
    try:
        render(args)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)
